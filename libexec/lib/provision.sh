# shellcheck shell=bash
# provision.sh - first-time setup: secrets, OEM scripts, ISO, container.

secrets_ensure() {
  if [ -s "$SECRETS" ]; then
    return 0
  fi
  mkdir -p "$(dirname -- "$SECRETS")"
  chmod 700 "$(dirname -- "$SECRETS")" 2>/dev/null || true
  local password
  password=$(gen_password)
  (
    umask 077
    {
      printf '# generated by porthole on %s\n' "$(date -Iseconds)"
      printf 'WINDOWS_PASSWORD=%s\n' "$password"
    } >"$SECRETS"
  )
  chmod 600 "$SECRETS"
  info "generated a Windows password (stored in $SECRETS, mode 600)"
}

render_settings() {
  PORTHOLE_CFG_USER="$VM_USER" \
  PORTHOLE_CFG_EXE="$APP_EXE" \
  PORTHOLE_CFG_ALIAS="$(cfg app.alias App)" \
  PORTHOLE_CFG_INSTALLER="$APP_INSTALLER" \
  PORTHOLE_CFG_INSTALL_ARGS="$(cfg_list app.install_args)" \
  PORTHOLE_CFG_STARTUP="$APP_STARTUP" \
  PORTHOLE_CFG_MAXIMIZED="$(cfg app.maximized true)" \
  PORTHOLE_CFG_DPI="$DPI_SCALE" \
  PORTHOLE_CFG_TWEAKS="$(cfg desktop.tweaks true)" \
  PORTHOLE_CFG_MONITORS="$MONITORS" \
  PORTHOLE_CFG_SHELL="$(cfg session.shell explorer)" \
  python3 - "$OEM/settings.json" <<'PY'
import json
import os
import sys


def env(name, default=""):
    value = os.environ.get(name)
    return default if value is None else value


settings = {
    "username": env("PORTHOLE_CFG_USER"),
    "app": {
        "exe": env("PORTHOLE_CFG_EXE"),
        "alias": env("PORTHOLE_CFG_ALIAS", "App"),
        "installer": env("PORTHOLE_CFG_INSTALLER"),
        "install_args": [a for a in env("PORTHOLE_CFG_INSTALL_ARGS").split("\n") if a],
        "startup": env("PORTHOLE_CFG_STARTUP", "true") == "true",
        "maximized": env("PORTHOLE_CFG_MAXIMIZED", "true") == "true",
    },
    "display": {
        "dpi_scale": int(env("PORTHOLE_CFG_DPI", "125") or 125),
    },
    "desktop_tweaks": env("PORTHOLE_CFG_TWEAKS", "true") == "true",
    "session": {
        "shell": env("PORTHOLE_CFG_SHELL", "explorer"),
    },
}

with open(sys.argv[1], "w", encoding="ascii") as handle:
    json.dump(settings, handle, ensure_ascii=True, indent=2)
    handle.write("\n")
PY
}

render_oem() {
  step "rendering OEM provisioning scripts"
  rm -rf "$OEM"
  mkdir -p "$OEM/lib"

  local file
  for file in "$PORTHOLE_ROOT"/windows/*.ps1 "$PORTHOLE_ROOT"/windows/*.bat; do
    [ -f "$file" ] || continue
    cp -f -- "$file" "$OEM/"
  done
  for file in "$PORTHOLE_ROOT"/windows/lib/*.ps1; do
    [ -f "$file" ] || continue
    cp -f -- "$file" "$OEM/lib/"
  done

  local icon="$PORTHOLE_ROOT/assets/icons/$PROFILE_ICON.ico"
  if [ -f "$icon" ]; then
    cp -f -- "$icon" "$OEM/$PROFILE_ICON.ico"
  fi

  render_settings
  debug "OEM folder ready: $OEM"
}

stage_installer() {
  [ -n "$APP_INSTALLER" ] || return 0
  local dest="$SHARED/$APP_INSTALLER"
  if [ -f "$dest" ]; then
    debug "installer already staged"
    return 0
  fi
  local candidate
  for candidate in \
    "$HOME/Downloads/$APP_INSTALLER" \
    "$HOME/下载/$APP_INSTALLER" \
    "$PORTHOLE_ROOT/vendor/$APP_INSTALLER"; do
    if [ -f "$candidate" ]; then
      step "staging $APP_INSTALLER"
      cp -f -- "$candidate" "$dest"
      return 0
    fi
  done
  warn "installer '$APP_INSTALLER' not found - drop it into $SHARED/ and re-run 'porthole provision'"
}

provision_wait() {
  local timeout=${1:-3600} waited=0 stage=""
  step "waiting for provisioning to finish (up to $((timeout / 60)) min)"
  info "the container installs Windows first, then runs C:\\OEM\\install.bat"

  while [ "$waited" -lt "$timeout" ]; do
    if [ -f "$STATUS_FILE" ]; then
      local current
      current=$(json_get "$STATUS_FILE" stage 2>/dev/null || printf '')
      if [ -n "$current" ] && [ "$current" != "$stage" ]; then
        stage=$current
        info "stage: $stage"
      fi
      case $stage in
        done) return 0 ;;
        failed)
          warn "provisioning reported a failure"
          warn "check C:\\OEM\\install.log inside the VM (porthole shell)"
          return 1
          ;;
      esac
    fi
    sleep 15
    waited=$((waited + 15))
    debug "waiting... ${waited}s"
  done

  warn "timed out after ${timeout}s"
  return 1
}

cmd_provision() {
  local wait=0 force=0
  while [ $# -gt 0 ]; do
    case $1 in
      -w|--wait) wait=1; shift ;;
      -f|--force) force=1; shift ;;
      *) die "provision: unknown argument: $1" ;;
    esac
  done

  require_runtime
  ensure_dirs
  secrets_ensure
  load_secret
  [ -n "${WINDOWS_PASSWORD:-}" ] || die "no Windows password in $SECRETS"

  iso_ensure
  vm_ensure_image
  render_oem
  stage_installer

  if vm_exists && [ "$force" -eq 0 ]; then
    info "container already exists - starting it"
    vm_start
  else
    vm_remove
    vm_create
  fi

  write_state "stage" "windows-install"
  write_state "provisioned_at" "$(date -Iseconds)"

  info "Windows is installing inside the container (25-35 min on ${VM_CPUS} vCPU)."
  info "watch it at http://127.0.0.1:$CONSOLE_PORT/"
  info "follow the container log with: porthole logs -f"

  if [ "$wait" -eq 1 ]; then
    provision_wait
  fi
}
